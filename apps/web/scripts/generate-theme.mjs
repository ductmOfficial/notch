#!/usr/bin/env node
/**
 * Generates app/theme.css: the Material Design 3 color scheme of Notch, light and dark, with
 * Google's Material Color Utilities. The palettes come from a lotus, stem and leaf included:
 * petal pink (primary), leaf green (tertiary, also "done"), stamen yellow ("upcoming") and
 * a cream neutral for the surfaces.
 *
 *   pnpm --filter web theme
 */
import { writeFile } from "node:fs/promises";
import {
  DynamicScheme,
  Hct,
  MaterialDynamicColors,
  TonalPalette,
  argbFromHex,
  hexFromArgb,
} from "@material/material-color-utilities";

const PETAL = "#D9668C";
const LEAF = "#4F8A3C";
const STAMEN = "#E3B23C";
/** Variant.TONAL_SPOT, the Material You default (the enum is not exported at runtime). */
const TONAL_SPOT = 2;

const ROLES = [
  "primary",
  "onPrimary",
  "primaryContainer",
  "onPrimaryContainer",
  "secondary",
  "onSecondary",
  "secondaryContainer",
  "onSecondaryContainer",
  "tertiary",
  "onTertiary",
  "tertiaryContainer",
  "onTertiaryContainer",
  "error",
  "onError",
  "errorContainer",
  "onErrorContainer",
  "surface",
  "surfaceDim",
  "surfaceBright",
  "onSurface",
  "onSurfaceVariant",
  "surfaceContainerLowest",
  "surfaceContainerLow",
  "surfaceContainer",
  "surfaceContainerHigh",
  "surfaceContainerHighest",
  "outline",
  "outlineVariant",
  "inverseSurface",
  "inverseOnSurface",
  "inversePrimary",
  "scrim",
  "shadow",
];

const hue = (hex) => Hct.fromInt(argbFromHex(hex)).hue;
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function block(dark) {
  const scheme = new DynamicScheme({
    sourceColorArgb: argbFromHex(PETAL),
    variant: TONAL_SPOT,
    contrastLevel: 0,
    isDark: dark,
    primaryPalette: TonalPalette.fromHueAndChroma(hue(PETAL), 48),
    secondaryPalette: TonalPalette.fromHueAndChroma(hue(PETAL), 16),
    tertiaryPalette: TonalPalette.fromHueAndChroma(hue(LEAF), 40),
    neutralPalette: TonalPalette.fromHueAndChroma(hue(STAMEN), 5),
    neutralVariantPalette: TonalPalette.fromHueAndChroma(hue(STAMEN), 9),
  });
  const lines = ROLES.map(
    (role) =>
      `  --md-sys-color-${kebab(role)}: ${hexFromArgb(MaterialDynamicColors[role].getArgb(scheme))};`,
  );
  // Status colors as M3 custom color groups: tones 40/100/90/10 light, 80/20/30/90 dark.
  for (const [name, hex] of Object.entries({ success: LEAF, warning: STAMEN })) {
    const palette = TonalPalette.fromInt(argbFromHex(hex));
    const [c, on, container, onContainer] = dark ? [80, 20, 30, 90] : [40, 100, 90, 10];
    lines.push(
      `  --md-sys-color-${name}: ${hexFromArgb(palette.tone(c))};`,
      `  --md-sys-color-on-${name}: ${hexFromArgb(palette.tone(on))};`,
      `  --md-sys-color-${name}-container: ${hexFromArgb(palette.tone(container))};`,
      `  --md-sys-color-on-${name}-container: ${hexFromArgb(palette.tone(onContainer))};`,
    );
  }
  return lines.join("\n");
}

const css = `/* Generated by scripts/generate-theme.mjs (lotus palette). Do not edit by hand. */
:root,
[data-theme="light"] {
  color-scheme: light;
${block(false)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${block(true).replaceAll("\n", "\n  ").replace(/^/, "  ")}
  }
}

[data-theme="dark"] {
  color-scheme: dark;
${block(true)}
}
`;

await writeFile(new URL("../app/theme.css", import.meta.url), css);
console.log("app/theme.css written");
