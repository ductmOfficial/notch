#!/usr/bin/env node
/**
 * Generates app/theme.css: the Material Design 3 color schemes of Notch, light and dark, with
 * Google's Material Color Utilities. Each scheme comes from a flower, stem and leaf included:
 * the petal (primary), the leaf (tertiary, also "done"), the heart of the flower ("upcoming"
 * and a warm neutral for the surfaces).
 *
 * - Lotus (sen), the default: pink petal, green leaf, yellow stamen.
 * - Daylily (huyên thảo, `data-palette="daylily"`): orange petal, its yellow throat, the green
 *   of its long leaves.
 *
 *   pnpm --filter web theme
 */
import { writeFile } from "node:fs/promises";
import {
  DynamicScheme,
  Hct,
  MaterialDynamicColors,
  TonalPalette,
  argbFromHex,
  hexFromArgb,
} from "@material/material-color-utilities";

const PALETTES = {
  lotus: { petal: "#D9668C", leaf: "#4F8A3C", heart: "#E3B23C" },
  daylily: { petal: "#E0702C", leaf: "#5B8A3A", heart: "#F2B33D" },
};
/** Variant.TONAL_SPOT, the Material You default (the enum is not exported at runtime). */
const TONAL_SPOT = 2;

const ROLES = [
  "primary",
  "onPrimary",
  "primaryContainer",
  "onPrimaryContainer",
  "secondary",
  "onSecondary",
  "secondaryContainer",
  "onSecondaryContainer",
  "tertiary",
  "onTertiary",
  "tertiaryContainer",
  "onTertiaryContainer",
  "error",
  "onError",
  "errorContainer",
  "onErrorContainer",
  "surface",
  "surfaceDim",
  "surfaceBright",
  "onSurface",
  "onSurfaceVariant",
  "surfaceContainerLowest",
  "surfaceContainerLow",
  "surfaceContainer",
  "surfaceContainerHigh",
  "surfaceContainerHighest",
  "outline",
  "outlineVariant",
  "inverseSurface",
  "inverseOnSurface",
  "inversePrimary",
  "scrim",
  "shadow",
];

const hue = (hex) => Hct.fromInt(argbFromHex(hex)).hue;
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function makeScheme({ petal, leaf, heart }, dark) {
  return new DynamicScheme({
    sourceColorArgb: argbFromHex(petal),
    variant: TONAL_SPOT,
    contrastLevel: 0,
    isDark: dark,
    primaryPalette: TonalPalette.fromHueAndChroma(hue(petal), 48),
    secondaryPalette: TonalPalette.fromHueAndChroma(hue(petal), 16),
    tertiaryPalette: TonalPalette.fromHueAndChroma(hue(leaf), 40),
    neutralPalette: TonalPalette.fromHueAndChroma(hue(heart), 5),
    neutralVariantPalette: TonalPalette.fromHueAndChroma(hue(heart), 9),
  });
}

function block(palette, dark) {
  const { leaf, heart } = palette;
  const scheme = makeScheme(palette, dark);
  const lines = ROLES.map(
    (role) =>
      `  --md-sys-color-${kebab(role)}: ${hexFromArgb(MaterialDynamicColors[role].getArgb(scheme))};`,
  );
  // Status colors as M3 custom color groups: tones 40/100/90/10 light, 80/20/30/90 dark.
  for (const [name, hex] of Object.entries({ success: leaf, warning: heart })) {
    const palette = TonalPalette.fromInt(argbFromHex(hex));
    const [c, on, container, onContainer] = dark ? [80, 20, 30, 90] : [40, 100, 90, 10];
    lines.push(
      `  --md-sys-color-${name}: ${hexFromArgb(palette.tone(c))};`,
      `  --md-sys-color-on-${name}: ${hexFromArgb(palette.tone(on))};`,
      `  --md-sys-color-${name}-container: ${hexFromArgb(palette.tone(container))};`,
      `  --md-sys-color-on-${name}-container: ${hexFromArgb(palette.tone(onContainer))};`,
    );
  }
  return lines.join("\n");
}

const indent = (text) => text.replaceAll("\n", "\n  ").replace(/^/, "  ");

/** Light, system-dark and forced-dark blocks; `p` scopes them to a palette. */
function schemeCss(palette, p = "") {
  const light = p ? `${p},\n${p}[data-theme="light"]` : `:root,\n[data-theme="light"]`;
  const systemDark = p ? `${p}:not([data-theme="light"])` : `:root:not([data-theme="light"])`;
  return `${light} {
  color-scheme: light;
${block(palette, false)}
}

@media (prefers-color-scheme: dark) {
  ${systemDark} {
    color-scheme: dark;
${indent(block(palette, true))}
  }
}

${p}[data-theme="dark"] {
  color-scheme: dark;
${block(palette, true)}
}
`;
}

const css = `/* Generated by scripts/generate-theme.mjs. Do not edit by hand. */

/* Lotus, the default palette. */
${schemeCss(PALETTES.lotus)}
/* Daylily. Its selectors are more specific or come later, so they win over the lotus. */
${schemeCss(PALETTES.daylily, '[data-palette="daylily"]')}`;

await writeFile(new URL("../app/theme.css", import.meta.url), css);
console.log("app/theme.css written");
