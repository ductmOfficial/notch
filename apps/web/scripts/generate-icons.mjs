#!/usr/bin/env node
/**
 * Generates components/icons.tsx from Material Symbols (Rounded, weight 400, Apache-2.0):
 * only the icons the app uses, as inline SVG paths, outlined and filled.
 *
 *   pnpm --filter web icons
 */
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const ICONS = {
  today: "home",
  growth: "monitoring",
  vaccines: "vaccines",
  add: "add",
  event: "event",
  scale: "scale",
  straighten: "straighten",
  edit: "edit",
  delete: "delete",
  close: "close",
  chevronRight: "chevron_right",
  back: "arrow_back",
  check: "check",
  settings: "settings",
  lightMode: "light_mode",
  darkMode: "dark_mode",
  contrast: "contrast",
  download: "download",
  copy: "content_copy",
  upload: "upload",
  pending: "radio_button_unchecked",
  calendarAdd: "calendar_add_on",
  linkOff: "link_off",
  refresh: "refresh",
};

const root = dirname(
  createRequire(import.meta.url).resolve("@material-symbols/svg-400/package.json"),
);
const pathOf = async (file) => {
  const svg = await readFile(join(root, "rounded", file), "utf8");
  const d = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!d) throw new Error(`No path in ${file}`);
  return d;
};

const entries = [];
for (const [key, name] of Object.entries(ICONS)) {
  entries.push(
    `  ${key}: ["${await pathOf(`${name}.svg`)}", "${await pathOf(`${name}-fill.svg`)}"],`,
  );
}

const tsx = `// Generated by scripts/generate-icons.mjs from Material Symbols Rounded (Apache-2.0). Do not edit.
const PATHS = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof PATHS;

/** A Material Symbol, 24px by default; decorative unless a label is given. */
export function Icon({
  name,
  filled = false,
  size = 24,
  label,
}: {
  name: IconName;
  filled?: boolean;
  size?: number;
  label?: string;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 -960 960 960"
      fill="currentColor"
      {...(label ? { role: "img", "aria-label": label } : { "aria-hidden": true })}
    >
      <path d={PATHS[name][filled ? 1 : 0]} />
    </svg>
  );
}
`;
await writeFile(new URL("../components/icons.tsx", import.meta.url), tsx);
console.log("components/icons.tsx written");
