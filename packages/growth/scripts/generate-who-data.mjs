// Generates src/data/*.ts from the WHO Child Growth Standards LMS tables
// published in the WHO `anthro` repository (one row per sex and day of age).
// Run with `pnpm --filter @notch/growth generate`. Pinned to a commit so the
// output is reproducible; bump ANTHRO_COMMIT deliberately and review the diff.
import { writeFile } from "node:fs/promises";

const ANTHRO_COMMIT = "b776d8a12b1c97369c748b561159fd2ec4f4db58";
const BASE = `https://raw.githubusercontent.com/WorldHealthOrganization/anthro/${ANTHRO_COMMIT}/data-raw/growthstandards`;
const MAX_AGE_DAYS = 1826;

const TABLES = [
  { file: "weianthro.txt", name: "weightForAge", out: "weight-for-age.ts", unit: "kg" },
  {
    file: "lenanthro.txt",
    name: "lengthHeightForAge",
    out: "length-height-for-age.ts",
    unit: "cm",
  },
  {
    file: "hcanthro.txt",
    name: "headCircumferenceForAge",
    out: "head-circumference-for-age.ts",
    unit: "cm",
  },
  { file: "bmianthro.txt", name: "bmiForAge", out: "bmi-for-age.ts", unit: "kg/m²" },
];

for (const table of TABLES) {
  const url = `${BASE}/${table.file}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${String(response.status)}`);
  const [header, ...rows] = (await response.text()).trim().split(/\r?\n/);
  const columns = header.split("\t");
  const at = (name) => {
    const index = columns.indexOf(name);
    if (index === -1) throw new Error(`${table.file}: missing column ${name}`);
    return index;
  };
  const [iSex, iAge, iL, iM, iS] = ["sex", "age", "l", "m", "s"].map(at);

  /** @type {{ male: number[], female: number[] }} */
  const bySex = { male: [], female: [] };
  for (const row of rows) {
    const cells = row.split("\t");
    const sex = cells[iSex] === "1" ? "male" : cells[iSex] === "2" ? "female" : undefined;
    if (!sex) throw new Error(`${table.file}: unexpected sex ${String(cells[iSex])}`);
    const age = Number(cells[iAge]);
    if (age !== bySex[sex].length / 3)
      throw new Error(`${table.file}: ${sex} day ${String(age)} out of order`);
    bySex[sex].push(Number(cells[iL]), Number(cells[iM]), Number(cells[iS]));
  }
  for (const sex of ["male", "female"]) {
    if (bySex[sex].length !== (MAX_AGE_DAYS + 1) * 3) {
      throw new Error(`${table.file}: ${sex} has ${String(bySex[sex].length / 3)} days`);
    }
    if (bySex[sex].some((n) => !Number.isFinite(n)))
      throw new Error(`${table.file}: non-numeric value`);
  }

  const source = `// Generated by scripts/generate-who-data.mjs. Do not edit.
// Source: WHO Child Growth Standards, ${url}
// © World Health Organization. Values in ${table.unit}.
// Flat [L, M, S] triples, one per day of age from 0 to ${String(MAX_AGE_DAYS)}.
import type { LmsTable } from "../types.js";

export const ${table.name}: LmsTable = {
  male: [${bySex.male.join(",")}],
  female: [${bySex.female.join(",")}],
};
`;
  await writeFile(new URL(`../src/data/${table.out}`, import.meta.url), source);
  console.log(`${table.out}: ${String(rows.length)} rows`);
}
